"""Create ``.env.local``: the local stand-in for Key Vault.

    python -m cloudops_devdata.envfile .env.local

Fresh random passwords on every machine, so no password is ever committed or
shared. Never overwrites a value: the passwords are baked into the container
volumes, and replacing them would lock you out of your own database (``make
reset`` wipes both together). Keys added in later steps are appended to an
existing file, leaving everything already in it untouched.
"""

from __future__ import annotations

import json
import os
import secrets
import sys
import uuid
from pathlib import Path

from cloudops_config.secrets import parse_env_file
from cloudops_devdata.tokens import new_signing_key

HEADER = """\
# Local development secrets: the stand-in for Key Vault. Generated by `make env`.
# Gitignored. Never commit, never copy to a shared location, never reuse in Azure.
# Keys map to Key Vault secret names: POSTGRES_APP_DSN <-> postgres-app-dsn.
"""


def render(passwords: dict[str, str]) -> str:
    def dsn(user: str, pw: str, db: str) -> str:
        return f"postgresql://{user}:{pw}@127.0.0.1:5432/{db}"

    p = passwords
    lines = [
        HEADER,
        "# Container provisioning (docker-compose.yml)",
        f"POSTGRES_SUPERUSER_PASSWORD={p['superuser']}",
        f"POSTGRES_MIGRATOR_PASSWORD={p['migrator']}",
        f"POSTGRES_APP_PASSWORD={p['app']}",
        f"POSTGRES_INGEST_PASSWORD={p['ingest']}",
        f"CLICKHOUSE_ADMIN_PASSWORD={p['ch_admin']}",
        f"CLICKHOUSE_TELEMETRY_PASSWORD={p['ch_telemetry']}",
        "",
        "# What the platform reads, by secret name",
        f"POSTGRES_APP_DSN={dsn('cloudops_app_local', p['app'], 'cloudops')}",
        f"POSTGRES_INGEST_DSN={dsn('cloudops_ingest_local', p['ingest'], 'cloudops')}",
        f"POSTGRES_MIGRATION_DSN={dsn('cloudops_migrator', p['migrator'], 'cloudops')}",
        "# Superuser: test provisioning only (make test). Nothing in the platform uses it.",
        f"POSTGRES_ADMIN_DSN={dsn('postgres', p['superuser'], 'postgres')}",
        "",
    ]
    return "\n".join(lines)


def later_keys() -> dict[str, str]:
    """Secrets added after step 02. Each is generated only if absent."""
    private, public = new_signing_key()
    return {
        # Step 04: the local dev token issuer (cloudops_devdata.tokens).
        "API_DEV_SIGNING_JWK": json.dumps(private, separators=(",", ":")),
        "API_DEV_JWKS": json.dumps(public, separators=(",", ":")),
        # Step 04: the default platform administrator (ADR 0002, D14). A random
        # object id: locally it is just the identity you mint tokens for.
        "PLATFORM_ADMIN_OID": str(uuid.uuid4()),
    }


def _append_missing(path: Path) -> int:
    present = parse_env_file(path.read_text(encoding="utf-8"), source=str(path))
    missing = {k: v for k, v in later_keys().items() if k not in present}
    if not missing:
        print(f"{path} is complete")
        return 0
    with path.open("a", encoding="utf-8") as f:
        f.write("\n# Added by a later step\n")
        f.writelines(f"{k}={v}\n" for k, v in missing.items())
    print(f"{path}: added {', '.join(sorted(missing))}")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m cloudops_devdata.envfile <path>", file=sys.stderr)
        return 2
    path = Path(argv[1])
    if path.exists():
        return _append_missing(path)
    keys = ("superuser", "migrator", "app", "ingest", "ch_admin", "ch_telemetry")
    # Hex only: safe in a URL, a shell and a compose file without escaping.
    content = render({k: secrets.token_hex(24) for k in keys})
    content += "".join(f"{k}={v}\n" for k, v in later_keys().items())
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"wrote {path} (mode 600)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
